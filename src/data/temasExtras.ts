/**
 * Base única das categorias temáticas usadas em vários jogos.
 * Cada tema tem: nome, uma dica (Impostor no Modo Casual e Quem Eu Sou)
 * e 5 palavras proibidas (Tabu). Completar usa só o nome.
 *
 * Formato compacto: t('Nome', 'Dica', 'proibida1|proibida2|proibida3|proibida4|proibida5')
 */

export interface Tema {
  nome: string;
  dica: string;
  proibidas: [string, string, string, string, string];
}

function t(nome: string, dica: string, proibidas: string): Tema {
  const p = proibidas.split('|').map((s) => s.trim());
  return { nome, dica, proibidas: [p[0], p[1], p[2], p[3], p[4]] };
}

